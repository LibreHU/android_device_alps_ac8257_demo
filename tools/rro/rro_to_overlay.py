#!/usr/bin/env python3
"""Write device-overlay values-mcc*/config.xml files from chosen per-carrier entries of a compiled RRO resources.arsc.
Static parse only. Usage: rro_to_overlay.py resources.arsc out_res_dir key1,key2,... [skip=qualifier:key,...]"""
import os, struct, sys
from xml.sax.saxutils import escape
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import arsc_dump as A

def entries(path):
    d = open(path, "rb").read()
    _, hsz, size, npkg = struct.unpack_from("<HHII", d, 0)
    gs, o = A.strpool(d, hsz)
    while o < len(d):
        ctype, chsz, csz = struct.unpack_from("<HHI", d, o)
        if ctype != 0x0200:
            o += csz; continue
        tstr_off, _, kstr_off, _ = struct.unpack_from("<IIII", d, o + 268)
        types, _ = A.strpool(d, o + tstr_off); keys, _ = A.strpool(d, o + kstr_off)
        p = o + chsz
        while p < o + csz:
            t, th, ts = struct.unpack_from("<HHI", d, p)
            if t == 0x0201:
                tid = d[p + 8]; ecount, estart = struct.unpack_from("<II", d, p + 12)
                c = d[p + 20:p + 20 + struct.unpack_from("<I", d, p + 20)[0]]
                mcc, mnc = struct.unpack_from("<HH", c, 4)
                offs = struct.unpack_from(f"<{ecount}I", d, p + th)
                for eo in offs:
                    if eo == 0xFFFFFFFF: continue
                    e = p + estart + eo
                    esz, flags, key = struct.unpack_from("<HHI", d, e)
                    if flags & 1:
                        cnt = struct.unpack_from("<I", d, e + 12)[0]; items = []; q = e + 16
                        for _ in range(cnt):
                            _, _, _, dt, data = struct.unpack_from("<IHBBI", d, q); items.append((dt, data)); q += 12
                        yield types[tid - 1], keys[key], mcc, mnc, ("array", items), gs
                    else:
                        _, _, dt, data = struct.unpack_from("<HBBI", d, e + 8)
                        yield types[tid - 1], keys[key], mcc, mnc, ("value", (dt, data)), gs
            p += ts
        o += csz

def text(dt, data, gs):
    if dt == 0x03: return gs[data]
    if dt == 0x12: return "true" if data else "false"
    if dt in (0x10, 0x11): return str(struct.unpack("<i", struct.pack("<I", data))[0])
    raise SystemExit(f"type 0x{dt:x} not handled")

def qual(mcc, mnc):
    if mnc == 0: return f"mcc{mcc}"
    if mnc == 0xFFFF: return f"mcc{mcc}-mnc00"
    width = 3 if 310 <= mcc <= 316 else 2
    return f"mcc{mcc}-mnc{mnc:0{width}d}"

arsc, out, keys = sys.argv[1], sys.argv[2], set(sys.argv[3].split(","))
skip = set(sys.argv[4].split("=", 1)[1].split(",")) if len(sys.argv) > 4 else set()
files = {}
for typ, key, mcc, mnc, val, gs in entries(arsc):
    if key not in keys or mcc == 0: continue
    q = qual(mcc, mnc)
    if f"{q}:{key}" in skip: continue
    if val[0] == "array":
        tag = "string-array" if typ == "array" and all(dt == 0x03 for dt, _ in val[1]) else "integer-array"
        body = "".join(f"\n        <item>{escape(text(dt, x, gs))}</item>" for dt, x in val[1])
        line = f'    <{tag} name="{key}" translatable="false">{body}\n    </{tag}>'
    else:
        line = f'    <{typ} name="{key}" translatable="false">{escape(text(*val[1], gs))}</{typ}>'
    files.setdefault(q, []).append(line)
for q, lines in sorted(files.items()):
    d = os.path.join(out, f"values-{q}"); os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "config.xml"), "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- LibreHU: per-carrier values of MediaTek\'s framework-res RRO of the stock vendor (vendor/overlay/\n'
                '     framework-res__auto_generated_rro.apk, removed by the ROM zip), kept for the boards with a modem: they only apply\n'
                '     with a SIM of this carrier. Generated by rro_to_overlay.py; values missing from LineageOS. -->\n<resources>\n')
        f.write("\n".join(lines) + "\n</resources>\n")
    print(q, len(lines))
